CREATE TABLE Cliente (
  cpf CHAR(11),
  nome VARCHAR(30) NOT NULL,
  sexo CHAR,
  data_nascimento DATE,
  pontos_crm INT DEFAULT 0 NOT NULL,
  indicado = CHAR(11),
  email CHAR(320) NOT NULL,
  rua CHAR(50),
  numero CHAR(6),
  bairro CHAR(10),
  cidade CHAR(20),
  estado CHAR(20),
  cep CHAR(8) NOT NULL,
  PRIMARY KEY(cpf),
  FOREIGN KEY (indicado) REFERENCES Cliente(cpf),
  CONSTRAINT chk_pontos CHECK (pontos_crm > 0),
  CONSTRAING chk_sexo CHECK (sexo = 'F' OR sexo = 'M')
)

CREATE TABLE Telefones(
  telefone CHAR(11),
  cpf_dono CHAR(11),
  PRIMARY KEY(cpf_dono, telefone),
  FOREIGN KEY (cpf_dono) REFERENCES Cliente(cpf)
)


CREATE TABLE Categoria(
  codigo INT GENERATED BY DEFAULT AS IDENTITY,
  nome CHAR(20) NOT NULL UNIQUE,
  PRIMARY KEY(codigo)
)

CREATE TABLE Transportadora(
  codigo INT GENERATED BY DEFAULT AS IDENTITY,
  site CHAR(100) NOT NULL,
  nome CHAR(50) NOT NULL,
  telefone CHAR(11) NOT NULL,
  email CHAR(320) NOT NULL,
  rua CHAR(50),
  numero CHAR(6),
  bairro CHAR(10),
  cidade CHAR(20),
  estado CHAR(20),
  cep CHAR(8) NOT NULL,
  PRIMARY KEY(codigo),
)

CREATE TABLE Fornecedor(
  cnpj CHAR(14),
  nome CHAR(50) NOT NULL,
  email CHAR(320) NOT NULL,
  telefone CHAR(11) NOT NULL,
  cep CHAR(8) NOT NULL,
  rua CHAR(50),
  numero CHAR(6),
  bairro CHAR(10),
  cidade CHAR(20),
  estado CHAR(20),
  PRIMARY KEY(cnpj),
)

CREATE TABLE OrdemDeCompra(
  codigo INT GENERATED BY DEFAULT AS IDENTITY,
  data_pedido TIMESTAMP NOT NULL,
  preco_frete NUMERIC(8, 2) NOT NULL,
  status CHAR(10) NOT NULL,
  desconto REAL NOT NULL DEFAULT 0,
  cod_transportadora INT NOT NULL,
  rua CHAR(50),
  numero CHAR(6),
  bairro CHAR(10),
  cidade CHAR(20),
  estado CHAR(20),
  cep CHAR(8) NOT NULL,
  cpf_cliente CHAR(11) NOT NULL,
  PRIMARY KEY(codigo),
  FOREIGN KEY (cpf_cliente) REFERENCES Cliente(cpf),
  FOREIGN KEY (cod_transportadora) REFERENCES Transportadora(codigo),
)

CREATE TABLE Produto(
  codigo INT GENERATED BY DEFAULT AS IDENTITY,
  cod_ordem INT,
  descricao_aval CHAR(300),
  nota INT,
  nome CHAR(20) NOT NULL,
  categoria INT NOT NULL,
  data_val DATE DEFAULT NULL,
  quantidade INT NOT NULL DEFAULT 1,
  descricao CHAR(300) NOT NULL,
  especificacao CHAR(300) NOT NULl,
  data_fabric DATE NOT NULL,
  preco_venda NUMERIC(8, 2) NOT NULL,
  preco_compra NUMERIC(8, 2) NOT NULL,
  PRIMARY KEY(codigo),
  FOREIGN KEY (categoria) REFERENCES Categoria(codigo),
  CONSTRAINT check_nota CHECK (nota <= 5 AND nota >= 0)
)

CREATE TABLE Fornece(
  cod_prod INT,
  cnpj_forn CHAR(14),
  PRIMARY KEY(cod_prod, cnpj_forn),
  FOREIGN KEY (cod_prod) REFERENCES Produto(codigo),
  FOREIGN KEY (cnpj_forn) REFERENCES Fornecedor(cnpj)
)

CREATE TABLE Possui(
  cod_ordem INT,
  cod_produto INT,
  quantidade INT NOT NULL DEFAULT 1,
  valor NUMERIC(8, 2) NOT NULL,
  PRIMARY KEY(cod_ordem, cod_produto),
  FOREIGN KEY (cod_ordem) REFERENCES OrdemDeCompra(codigo),
  FOREIGN KEY (cod_produto) REFERENCES Produto(codigo),
)


CREATE TABLE NotaFiscal(
  numero CHAR(9) NOT NULL,
  serie CHAR(3) NOT NULL,
  valor_total NUMERIC(8, 2) NOT NULL,
  inscricao_estadual CHAR(14) NOT NULL,
  chave_acesso CHAR(44) NOT NULL,
  codigo_ordem CHAR(10) NOT NULL,
  PRIMARY KEY(chave_acesso),
  FOREIGN KEY (codigo_ordem) REFERENCES OrdemDeCompra(codigo),
)


