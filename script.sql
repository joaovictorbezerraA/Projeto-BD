CREATE TABLE Cliente (
  cpf CHAR(11),
  nome VARCHAR(30) NOT NULL,
  sexo CHAR,
  data_nascimento DATE,
  pontos_crm INT DEFAULT 0,
  email CHAR(320),
  rua VARCHAR(50),
  numero VARCHAR(6),
  bairro VARCHAR(10),
  cidade VARCHAR(20),
  estado VARCHAR(20),
  cep CHAR(8) NOT NULL,
  PRIMARY KEY(cpf),
  CONSTRAINT chk_cpf_tamanho CHECK (LENGTH(TRIM(cpf)) = 11),
  CONSTRAINT chk_cep_tamanho CHECK (LENGTH(TRIM(cep)) = 8)
)

CREATE TABLE Telefones(
  telefone CHAR(11),
  cpf_dono CHAR(11),
  PRIMARY KEY(cpf_dono, telefone),
  FOREIGN KEY (cpf_dono) REFERENCES Cliente(cpf)
  CONSTRAINT chk_telefone_tamanho CHECK (LENGTH(TRIM(telefone)) = 11)
)


CREATE TABLE Categoria(
  codigo INT GENERATED BY DEFAULT AS IDENTITY,
  nome VARCHAR(20) NOT NULL UNIQUE,
  PRIMARY KEY(codigo)
)

CREATE TABLE Transportadora(
  codigo INT GENERATED BY DEFAULT AS IDENTITY,
  site VARCHAR(100),
  nome VARCHAR(50),
  telefone CHAR(11),
  email CHAR(320),
  rua VARCHAR(50),
  numero VARCHAR(6),
  bairro VARCHAR(10),
  cidade VARCHAR(20),
  estado VARCHAR(20),
  cep CHAR(8) NOT NULL,
  PRIMARY KEY(codigo),
  CONSTRAINT chk_codigo_tamanho CHECK (LENGTH(TRIM(codigo)) = 14)
  CONSTRAINT chk_telefone_tamanho CHECK (LENGTH(TRIM(telefone)) = 11)
)

CREATE TABLE Fornecedor(
  cnpj CHAR(14),
  nome VARCHAR(50) NOT NULL,
  email CHAR(320),
  telefone CHAR(11),
  cep CHAR(8) NOT NULL,
  rua VARCHAR(50),
  numero VARCHAR(6),
  bairro VARCHAR(10),
  cidade VARCHAR(20),
  estado VARCHAR(20),
  PRIMARY KEY(cnpj),
  CONSTRAINT chk_telefone_tamanho CHECK (LENGTH(TRIM(telefone)) = 11),
  CONSTRAINT chk_cep_tamanho CHECK (LENGTH(TRIM(cep)) = 8)
  CONSTRAINT chk_cnpj_tamanho CHECK (LENGTH(TRIM(cnpj)) = 14),
)

CREATE TABLE OrdemDeCompra(
  codigo INT GENERATED BY DEFAULT AS IDENTITY,
  data_pedido TIMESTAMP NOT NULL,
  preco_frete NUMERIC(8, 2) NOT NULL,
  status VARCHAR(10) NOT NULL,
  desconto REAL,
  cod_transportadora CHAR(14) NOT NULL,
  rua VARCHAR(50),
  numero VARCHAR(6),
  bairro VARCHAR(10),
  cidade VARCHAR(20),
  estado VARCHAR(20),
  cep CHAR(8) NOT NULL,
  cpf_cliente CHAR(11) NOT NULL,
  PRIMARY KEY(codigo),
  FOREIGN KEY (cpf_cliente) REFERENCES Cliente(cpf),
  FOREIGN KEY (cod_transportadora) REFERENCES Transportadora(codigo),
  CONSTRAINT chk_cep_tamanho CHECK (LENGTH(TRIM(cep)) = 8)
)

CREATE TABLE Produto(
  codigo INT GENERATED BY DEFAULT AS IDENTITY,
  cod_ordem INT,
  descricao_aval CHAR(300),
  nota INT,
  nome CHAR(20) NOT NULL,
  categoria INT NOT NULL,
  data_val DATE DEFAULT NULL,
  quantidade INT NOT NULL DEFAULT 1,
  descricao VARCHAR(300),
  especificacao VARCHAR(300),
  data_fabric DATE,
  preco_venda NUMERIC(8, 2) NOT NULL,
  preco_compra NUMERIC(8, 2) NOT NULL,
  PRIMARY KEY(codigo),
  FOREIGN KEY (categoria) REFERENCES Categoria(codigo),
  CONSTRAINT check_nota CHECK (nota <= 5 AND nota >= 0)
)

CREATE TABLE Fornece(
  cod_prod INT,
  cnpj_forn CHAR(14),
  PRIMARY KEY(cod_prod, cnpj_forn),
  FOREIGN KEY (cod_prod) REFERENCES Produto(codigo),
  FOREIGN KEY (cnpj_forn) REFERENCES Fornecedor(cnpj)
)

CREATE TABLE Possui(
  cod_ordem INT,
  cod_produto INT,
  quantidade INT NOT NULL DEFAULT 1,
  valor NUMERIC(8, 2) NOT NULL,
  PRIMARY KEY(cod_ordem, cod_produto),
  FOREIGN KEY (cod_ordem) REFERENCES OrdemDeCompra(codigo),
  FOREIGN KEY (cod_produto) REFERENCES Produto(codigo)
)


CREATE TABLE NotaFiscal(
  numero CHAR(9) NOT NULL,
  serie CHAR(3) NOT NULL,
  valor_total NUMERIC(8, 2) NOT NULL,
  inscricao_estadual CHAR(14) NOT NULL,
  chave_acesso CHAR(44) NOT NULL,
  codigo_ordem CHAR(10) NOT NULL,
  PRIMARY KEY(chave_acesso),
  FOREIGN KEY (codigo_ordem) REFERENCES OrdemDeCompra(codigo),
  CONSTRAINT chk_numero_tamanho CHECK (LENGTH(TRIM(numero)) = 9),
  CONSTRAINT chk_chave_acesso_tamanho CHECK (LENGTH(TRIM(chave_acesso)) = 44),
  CONSTRAINT chk_serie_tamanho CHECK (LENGTH(TRIM(serie)) = 3)
)


